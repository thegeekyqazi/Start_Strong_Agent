// Generate src/generated.ts from the canonical JSON Schema exported by the Python
// contracts package (packages/contracts/schema/strongstart-contracts.schema.json).
//   --write  regenerate the file
//   --check  exit 1 if the committed file differs from a fresh generation (drift)
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const schemaPath = resolve(here, '../../schema/strongstart-contracts.schema.json')
const outPath = resolve(here, '../src/generated.ts')
const mode = process.argv[2]
if (mode !== '--write' && mode !== '--check') {
  console.error('usage: generate.mjs --write|--check')
  process.exit(2)
}

const schema = JSON.parse(await readFile(schemaPath, 'utf8'))

// Pydantic adds a `title` to every property; json-schema-to-typescript would turn each
// into a named alias. Keep titles only on the named $defs so output stays readable.
function stripPropertyTitles(node, keep) {
  if (Array.isArray(node)) return node.forEach((n) => stripPropertyTitles(n, false))
  if (node === null || typeof node !== 'object') return
  if (!keep) delete node.title
  for (const [key, value] of Object.entries(node)) {
    if (key === '$defs') Object.values(value).forEach((d) => stripPropertyTitles(d, true))
    else stripPropertyTitles(value, false)
  }
}
stripPropertyTitles(schema, true)
const banner =
  '/* GENERATED by packages/contracts/ts/scripts/generate.mjs from\n' +
  ' * packages/contracts/schema/strongstart-contracts.schema.json. DO NOT EDIT. */'
const ts = await compile(
  { ...schema, type: 'object', additionalProperties: false },
  'StrongStartContracts',
  {
    bannerComment: banner,
    unreachableDefinitions: true,
    additionalProperties: false,
    format: true,
    style: { semi: false, singleQuote: true, printWidth: 100 },
  },
)

if (mode === '--write') {
  await writeFile(outPath, ts)
  console.log(`wrote ${outPath}`)
} else {
  let current = ''
  try {
    current = await readFile(outPath, 'utf8')
  } catch {
    // missing file counts as drift
  }
  if (current !== ts) {
    console.error('contract drift: generated.ts differs from the schema. Run `make contracts`.')
    process.exit(1)
  }
  console.log('contracts: TypeScript declarations match the schema')
}
